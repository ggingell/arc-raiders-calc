#!/usr/bin/env node
/**
 * items-with-recipes.js
 *
 * Reads all `*.json` files from ./arcraiders-data/items,
 * extracts the required fields, filters out items that do not
 * contain a recipe, and writes the resulting array to
 * ./items-with-recipes.js (next to this script).
 */

const fs = require("fs").promises;
const path = require("path");

// ------------------------------------------------------------------
// 1️⃣  Locate the folder that contains the raw item JSON files
// ------------------------------------------------------------------
const itemsFolder = path.resolve(__dirname, "./arcraiders-data/items/");

// ------------------------------------------------------------------
// 2️⃣  Load every JSON file from that folder into an array
// ------------------------------------------------------------------
async function loadAllItemFiles() {
  const fileNames = await fs.readdir(itemsFolder);
  const items = [];

  for (const fileName of fileNames) {
    // only consider *.json files
    if (path.extname(fileName).toLowerCase() !== ".json") continue;

    const filePath = path.join(itemsFolder, fileName);

    try {
      const raw = await fs.readFile(filePath, "utf8");
      const parsed = JSON.parse(raw);
      items.push(parsed);
    } catch (err) {
      console.error(`❌  Could not read/parse "${fileName}": ${err.message}`);
    }
  }
  return items;
}

// ------------------------------------------------------------------
// 3️⃣  Map each item to the shape we want and filter out the ones
//      without a recipe
// ------------------------------------------------------------------
function createCraftingObject(items) {
  const result = {};
  items
    // .filter((item) => item.recipe != null) // skip items with no recipe
    .forEach((item) => {
      if (!item.id) {
        return;
      }

      const simplified = {
        id: item.id,
        name: item.name?.en ?? null, // english name
        rarity: item.rarity,
        stackSize: item.stackSize ?? 1,
        recipe: item.recipe,
        craftBench: item.craftBench,
        type: item.type,
        isWeapon: item.isWeapon ?? false,
      };

      result[item.id] = simplified;
    });
    
  return result;
}

// ------------------------------------------------------------------
// 4️⃣  Write the resulting array to a JS file next to this script
// ------------------------------------------------------------------
async function writeOutput(mapped) {
  const outPath = path.resolve(__dirname, "./items-with-recipes.js");
  const fileContent = `// Generated by items-with-recipes.js – do not edit manually
export const ITEMS_WITH_RECIPES = ${JSON.stringify(mapped, null, 2)};`;

  await fs.writeFile(outPath, fileContent, "utf8");
  //   console.log(`✅  Wrote ${Object.keys(mapped).length} items to "${outPath}"`);
}

// ------------------------------------------------------------------
// 5️⃣  Glue everything together
// ------------------------------------------------------------------
(async () => {
  try {
    const rawItems = await loadAllItemFiles();
    const mapped = createCraftingObject(rawItems);
    await writeOutput(mapped);
  } catch (err) {
    console.error(`❌  Unexpected error: ${err.stack}`);
    process.exit(1);
  }
})();
